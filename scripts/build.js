"use strict";

/**
 * Static build for hosts without Node (GitHub Pages, Netlify, Vercel).
 *
 * - Copies ./public to ./dist unchanged.
 * - Fails if index.html, the CSS/JS or any photo/video/thumbnail in js/data.js
 *   points at a local file that does not exist, so a broken path never ships.
 * - Writes dist/404.html, which sends clean URLs such as /about back to the
 *   site's home page (the same job server.js does for the Node version).
 *
 * BASE_PATH is the folder the site is served from, e.g. "/abhinav-kunwar-portfolio"
 * for https://<user>.github.io/abhinav-kunwar-portfolio/. The GitHub Actions
 * workflow sets it automatically; it defaults to "" (site at the domain root).
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "public");
const OUT = path.join(ROOT, "dist");
const BASE = (process.env.BASE_PATH || "").replace(/\/+$/, "");

const isLocal = (ref) => ref && !/^(https?:|mailto:|tel:|data:|#|\/\/)/i.test(ref);

function collectRefs() {
  const refs = new Set();
  const html = fs.readFileSync(path.join(SRC, "index.html"), "utf8");
  for (const m of html.matchAll(/\b(?:src|href)="([^"]+)"/g)) refs.add(m[1]);

  const css = fs.readFileSync(path.join(SRC, "css", "styles.css"), "utf8");
  for (const m of css.matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)) {
    refs.add(path.posix.join("css", m[1]));
  }

  // Paths to photos, videos and thumbnails in the content file.
  const data = fs.readFileSync(path.join(SRC, "js", "data.js"), "utf8");
  for (const m of data.matchAll(/["']([^"'\s]+\.(?:webp|png|jpe?g|gif|svg|mp4|webm|mov))["']/gi)) refs.add(m[1]);

  return [...refs].filter(isLocal).map((r) => r.split(/[?#]/)[0]);
}

const missing = collectRefs().filter((ref) => {
  if (ref.startsWith("/")) return true; // root-absolute paths break when the site lives in a sub-folder
  return !fs.existsSync(path.join(SRC, ref));
});
if (missing.length) {
  console.error("Build failed. These paths are missing from public/ or start with '/':");
  for (const m of missing) console.error("  - " + m);
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(SRC, OUT, { recursive: true });

// CMS settings for the static copy: read published projects straight from Sanity's public API.
// Values come from environment variables (GitHub repository variables in the Pages workflow).
const sanityProject = (process.env.SANITY_PROJECT_ID || "").trim();
const cmsConfig = /^[a-z0-9-]+$/i.test(sanityProject)
  ? {
      enabled: true,
      projectId: sanityProject,
      dataset: (process.env.SANITY_DATASET || "production").trim(),
      apiVersion: (process.env.SANITY_API_VERSION || "2025-02-19").trim(),
      query: require("../lib/site-query"),
    }
  : { enabled: false };
fs.writeFileSync(
  path.join(OUT, "js", "cms-config.js"),
  `/* Generated by scripts/build.js. */\nwindow.CMS_CONFIG = ${JSON.stringify(cmsConfig)};\n`
);
// index.html: open the connection to Sanity's API early, and give CSS/JS a version so returning
// visitors always get the latest files (GitHub Pages caches them for a few minutes otherwise).
{
  const crypto = require("crypto");
  const indexPath = path.join(OUT, "index.html");
  let html = fs.readFileSync(indexPath, "utf8");
  html = html.replace("<!-- cms:preconnect -->", cmsConfig.enabled
    ? `<link rel="preconnect" href="https://${cmsConfig.projectId}.apicdn.sanity.io" crossorigin>`
    : "");
  html = html.replace(/\b(src|href)="((?:css|js)\/[^"?#]+\.(?:css|js))"/g, (m, attr, ref) => {
    const hash = crypto.createHash("sha1").update(fs.readFileSync(path.join(OUT, ref))).digest("hex").slice(0, 8);
    return `${attr}="${ref}?v=${hash}"`;
  });
  fs.writeFileSync(indexPath, html);
}
console.log(cmsConfig.enabled ? `CMS: Sanity ${cmsConfig.projectId}/${cmsConfig.dataset}` : "CMS: off (SANITY_PROJECT_ID not set) — using projects from data.js");

const home = `${BASE}/`;
// Pages inside the Studio (e.g. /studio/structure/project) have no file of their own on a static host,
// so they arrive here: load the Studio's page in place and let it open the right screen.
// Every other unknown address goes back to the portfolio.
const studio = `${BASE}/studio`;
fs.writeFileSync(
  path.join(OUT, "404.html"),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Abhinav Kunwar Video Portfolio</title>
<meta name="robots" content="noindex">
<noscript><meta http-equiv="refresh" content="0; url=${home}"></noscript>
<script>
(function () {
  var home = ${JSON.stringify(home)}, studio = ${JSON.stringify(studio)}, p = location.pathname;
  if (p === studio || p.indexOf(studio + "/") === 0) {
    fetch(studio + "/index.html", { cache: "no-cache" })
      .then(function (r) { if (!r.ok) throw new Error(r.status); return r.text(); })
      .then(function (html) { document.open(); document.write(html); document.close(); })
      .catch(function () { location.replace(home); });   // no Studio on this copy of the site
  } else {
    location.replace(home + location.hash);
  }
})();
</script>
</head>
<body><a href="${home}">Go to the portfolio</a></body>
</html>
`
);

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    e.isDirectory() ? walk(p) : files.push(p);
  }
})(OUT);
const bytes = files.reduce((n, f) => n + fs.statSync(f).size, 0);
console.log(`Built dist/ — ${files.length} files, ${(bytes / 1024).toFixed(0)} KB, base path "${home}"`);
