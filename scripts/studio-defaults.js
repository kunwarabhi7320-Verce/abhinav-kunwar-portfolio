"use strict";

/**
 * Writes studio/schemaTypes/siteDefaults.js from public/js/data.js, so the Studio's "Website text"
 * form opens already filled in with the text the site shows today.
 * Run after changing the text in data.js:  node scripts/studio-defaults.js
 * (`node scripts/studio-defaults.js --check` fails if the two have drifted apart.)
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "studio", "schemaTypes", "siteDefaults.js");
const src = fs.readFileSync(path.join(ROOT, "public", "js", "data.js"), "utf8");
const ctx = {};
vm.runInNewContext(`${src}\n;this.D = { CONFIG, TEXT, EXPERIENCE, TESTIMONIALS, TOOLS, TICKER, WORKFLOW, CATS };`, ctx);
const { CONFIG, TEXT, EXPERIENCE, TESTIMONIALS, TOOLS, TICKER, WORKFLOW, CATS } = ctx.D;

// Sanity needs a stable _key on every list item.
const keyed = (list, prefix, map) => list.map((x, i) => ({ _key: `${prefix}${i + 1}`, ...map(x, i) }));
const COLOR = { ai: "ai", mg: "mg", a: "ai", m: "mg" };

const defaults = {
  ...TEXT,
  email: CONFIG.email, phone: CONFIG.phone, linkedin: CONFIG.linkedin, calendly: CONFIG.calendly, location: CONFIG.location,
  experience: keyed(EXPERIENCE, "exp", e => ({
    _type: "experienceItem", role: e.role, org: e.org, when: e.when, current: !!e.now, ...(e.text ? { text: e.text } : {}),
    ...(e.sub ? { clients: keyed(e.sub, "client", c => ({ _type: "clientItem", name: c.org, text: c.text })) } : {}),
  })),
  testimonials: keyed(TESTIMONIALS, "quote", t => ({ _type: "testimonialItem", name: t.name, role: t.role, quote: t.quote, practice: t.cat })),
  tools: keyed(TOOLS, "tools", g => ({ _type: "toolGroup", name: g.name, color: COLOR[g.tone] || "neutral", items: g.items })),
  ticker: keyed(TICKER, "tick", ([text, c]) => ({ _type: "tickerItem", text, color: COLOR[c] || "neutral" })),
  workflow: keyed(WORKFLOW, "step", w => ({ _type: "workflowStep", title: w.t, text: w.d })),
};
for (const [k, c] of Object.entries(CATS)) {
  defaults[`${k}Blurb`] = c.blurb;
  defaults[`${k}Intro`] = c.intro;
  defaults[`${k}ShortDetail`] = c.short.detail;
  defaults[`${k}LongDetail`] = c.long.detail;
}

const file = `/* Generated by scripts/studio-defaults.js from public/js/data.js. Do not edit by hand. */\nexport const siteDefaults = ${JSON.stringify(defaults, null, 2)}\n`;
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== file) { console.error("studio/schemaTypes/siteDefaults.js is out of date. Run: node scripts/studio-defaults.js"); process.exit(1); }
  console.log("Studio defaults match data.js");
} else {
  fs.writeFileSync(OUT, file);
  console.log("Wrote " + path.relative(ROOT, OUT));
}
