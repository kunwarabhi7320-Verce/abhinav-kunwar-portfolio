"use strict";

/**
 * Sanity content for the portfolio (read-only).
 *
 *   GET /api/projects      published projects as JSON (cached in memory)
 *   GET /js/cms-config.js  tells the browser whether the CMS is on and where to read from
 *
 * Configuration comes only from environment variables (see .env.example). No token is used:
 * the dataset must be public, so the site can read published content and nothing else.
 */
const express = require("express");
const { createClient } = require("@sanity/client");
const PROJECTS_QUERY = require("./projects-query");

const projectId = (process.env.SANITY_PROJECT_ID || "").trim();
const dataset = (process.env.SANITY_DATASET || "production").trim();
const apiVersion = (process.env.SANITY_API_VERSION || "2025-02-19").trim();
const cacheSeconds = Math.max(0, Number(process.env.SANITY_CACHE_SECONDS ?? 60) || 0);
// Tests can point the client at a local mock; production always uses Sanity's own API host.
const apiHost = process.env.SANITY_API_HOST || undefined;

const configured = /^[a-z0-9-]+$/i.test(projectId) && /^[a-z0-9_-]+$/i.test(dataset);
const client = configured
  ? createClient({ projectId, dataset, apiVersion, useCdn: true, perspective: "published", ...(apiHost ? { apiHost } : {}) })
  : null;

let cache = null;       // { body, at }
let inflight = null;

async function fetchProjects() {
  if (cache && Date.now() - cache.at < cacheSeconds * 1000) return cache.body;
  if (!inflight) {
    inflight = client
      .fetch(PROJECTS_QUERY, {}, { perspective: "published", useCdn: true })
      .then(projects => {
        cache = { body: { projects: Array.isArray(projects) ? projects : [], fetchedAt: new Date().toISOString() }, at: Date.now() };
        return cache.body;
      })
      .finally(() => { inflight = null; });
  }
  return inflight;
}

function describeSetup() {
  if (!configured) return "Sanity CMS: off (set SANITY_PROJECT_ID to turn it on; the site uses the projects in public/js/data.js)";
  return `Sanity CMS: reading published projects from ${projectId}/${dataset} (API ${apiVersion}, cache ${cacheSeconds}s)`;
}

const router = express.Router();

router.get("/js/cms-config.js", (req, res) => {
  const cfg = configured
    ? { enabled: true, endpoint: "/api/projects" }
    : { enabled: false };
  res.type("application/javascript").set("Cache-Control", "no-cache")
    .send(`/* Generated by the server from environment variables. */\nwindow.CMS_CONFIG = ${JSON.stringify(cfg)};\n`);
});

router.get("/api/projects", async (req, res) => {
  res.set("Cache-Control", "no-cache");
  if (!configured) return res.status(503).json({ error: "The CMS is not configured on this server." });
  try {
    res.json(await fetchProjects());
  } catch (err) {
    const status = err.statusCode || err.response?.statusCode;
    console.error(`Sanity fetch failed${status ? ` (HTTP ${status})` : ""}: ${err.message?.slice(0, 160)}`);
    if (cache) return res.set("X-Content-Stale", "1").json({ ...cache.body, stale: true });  // keep the site up with the last good copy
    res.status(502).json({ error: "Projects are temporarily unavailable." });
  }
});

module.exports = { router, describeSetup, configured };
